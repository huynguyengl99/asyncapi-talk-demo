from chanx.fast_channels import asyncapi_docs, asyncapi_spec_json
from chanx.fast_channels.type_defs import AsyncAPIConfig
from fast_channels.layers import InMemoryChannelLayer, has_layers, register_channel_layer
from fastapi import FastAPI, Request
from fastapi.responses import HTMLResponse, JSONResponse

from .consumer import HealthConsumer

if not has_layers():
    register_channel_layer("chat", InMemoryChannelLayer())

app = FastAPI(title="Room chat")

asyncapi_config = AsyncAPIConfig(
    title="Room chat API",
    version="1.0.0",
    description="Generated by chanx from the typed handlers in app/consumer.py",
)


@app.get("/asyncapi")
async def asyncapi_page(request: Request) -> HTMLResponse:
    return await asyncapi_docs(request=request, app=app, config=asyncapi_config)


@app.get("/asyncapi.json")
async def asyncapi_json(request: Request) -> JSONResponse:
    return await asyncapi_spec_json(request=request, app=app, config=asyncapi_config)


ws = FastAPI()
ws.router.add_websocket_route("/health", HealthConsumer.as_asgi())
app.mount("/ws", ws)
